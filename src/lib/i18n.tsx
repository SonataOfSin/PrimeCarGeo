type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (key: string) => string };
const LangCtx = createContext<Ctx>({ lang: "en", setLang: () => {}, t: (k) => k });

export const LanguageProvider = ({ children }: { children: ReactNode }) => {
  const [lang, setLangState] = useState<Lang>(() => {
    if (typeof window === "undefined") return "en";
    const v = localStorage.getItem("pv.lang");
    return v === "ka" ? "ka" : v === "ru" ? "ru" : "en";
  });
  useEffect(() => {
    document.documentElement.lang = lang;
    localStorage.setItem("pv.lang", lang);
  }, [lang]);
  const t = (k: string) => DICT[lang][k] ?? DICT.en[k] ?? k;
  return <LangCtx.Provider value={{ lang, setLang: setLangState, t }}>{children}</LangCtx.Provider>;
};

